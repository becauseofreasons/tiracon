/* Generates C++ data from the WebApp (the WebApp stays the reference, the plugin build needs no JS):
 *   src/core/gen/parts_data.inc   parts list (emulator/js/parts.js) for the tolerance model
 *   src/core/gen/factory_ram.inc  2 KB RAM image with the 32 factory programs (emulator/js/factory.js)
 *   src/core/gen/param_names.inc  parameter names, groups and value names (emulator/js/params.js, ASCII)
 * Run again after changes to parts.js, factory.js or the program format:
 *   node vst3/tools/gen_data.js
 */
'use strict';
var fs = require('fs');
var path = require('path');
// the WebApp (not part of this repository); default: next to vst3/, or set TIRACON_WEBAPP=<emulator folder>
var JS = path.join(process.env.TIRACON_WEBAPP || path.join(__dirname, '..', '..', 'emulator'), 'js');
var OUT = path.join(__dirname, '..', 'src', 'core', 'gen');
var Parts = require(path.join(JS, 'parts.js'));
var Factory = require(path.join(JS, 'factory.js'));
var Params = require(path.join(JS, 'params.js'));
var ROM = path.join(__dirname, '..', 'firmware', 'tiracon_mod.bin');

function cstr(s) { return JSON.stringify(String(s)); }       // JSON string = valid C string for this data
function num(x) { return x ? x.toPrecision(17) : '0'; }

fs.mkdirSync(OUT, { recursive: true });
var head = '// generated by vst3/tools/gen_data.js - do not edit\n';

var p = head;
['DLP', 'ALP', 'KLP'].forEach(function (board) {
  p += 'static const PartDef PARTS_' + board + '[] = {\n';
  Parts[board].forEach(function (x) {
    p += '  {' + [cstr(x[0]), num(x[1]), cstr(x[2]), cstr(x[3] || ''), cstr(x[4] || '')].join(', ') + '},\n';
  });
  p += '};\n';
});
fs.writeFileSync(path.join(OUT, 'parts_data.inc'), p);

var ram = Factory.ram(), r = head + 'static const unsigned char FACTORY_RAM[2048] = {\n';
for (var i = 0; i < ram.length; i += 16) r += '  ' + Array.prototype.slice.call(ram, i, i + 16).join(', ') + ',\n';
r += '};\n';
fs.writeFileSync(path.join(OUT, 'factory_ram.inc'), r);
// parameter names for the DAW and the editor (plain ASCII: some hosts show nothing else)
Params.setRom(fs.readFileSync(ROM));
var SYM = { rampUp: 'RAMP UP', rampDown: 'RAMP DOWN', tri: 'TRIANGLE' };
var SYMCODE = { saw: 1, pulse: 2, square: 3 };
function ascii(t) { return String(t).replace(/ · /g, ' ').replace(/×/g, 'x').replace(/[^\x20-\x7E]/g, '?'); }
var n = head + '// number, group index, title, sheet label, value names (|), foot, symbol (1 saw 2 pulse 3 square), new, global\n' +
  'static const char* const GROUP_NAMES[] = {' + Params.GROUPS.map(function (g) { return cstr(g.name); }).join(', ') + '};\n' +
  'static const ParamName PARAM_NAMES[] = {\n', cnt = 0;
Params.GROUPS.forEach(function (g, gi) {
  g.p.forEach(function (no) {
    if (!Params.has(no)) return;
    var p = Params.P[no];
    var vals = p.vals ? p.vals.map(function (v) { return ascii(typeof v === 'string' ? v : SYM[v.sym] || v.sym); }).join('|') : '';
    n += '  {' + [no, gi, cstr(ascii(Params.title(no))), cstr(ascii(p.lbl || p.name || '')), cstr(vals), cstr(ascii(p.foot || '')),
      p.sym ? SYMCODE[p.sym] || 0 : 0, p.isNew ? 1 : 0, p.glob ? 1 : 0].join(', ') + '},\n';
    cnt++;
  });
});
n += '};\n';
fs.writeFileSync(path.join(OUT, 'param_names.inc'), n);
console.log('geschrieben: parts_data.inc (' + Parts.DLP.length + '/' + Parts.ALP.length + '/' + Parts.KLP.length +
  ' Bauteile), factory_ram.inc (' + ram.length + ' Byte), param_names.inc (' + cnt + ' Parameter)');
